function namingSentence(row) {
  const meaning = clean(row['意味']);
  const score = Number(row['おすすめ度']) || 0;
  const focus = meaningParts(meaning)[0] || row['漢字'];
  if (score <= 25) {
    return `名づけでは、「${focus}」という本来の語義を確かめ、読みや他の字との組み合わせを含めて丁寧に選びたい字です。`;
  }
  const matched = IMPRESSION_RULES.find((rule) => rule.pattern.test(meaning));
  if (matched) return `名前では、${matched.text}`;

  return `名前では、「${focus}」という意味を軸に、読みや他の字との調和を考えられます。`;
}

function variantText(row, standardReview) {
  const glyphType = clean(row['字形種別']) || '別字形';
  const standard = clean(row['標準字体']);
  return `「${row['漢字']}」は「${standard}」の${glyphType}です。${standardReview.text}`;
}

function main() {
  const master = JSON.parse(fs.readFileSync(MASTER_PATH, 'utf8'));
  const reviewFile = JSON.parse(fs.readFileSync(REVIEW_PATH, 'utf8'));
  const reviews = reviewFile.entries || {};
  let added = 0;

  for (const row of master) {
    const kanji = clean(row['漢字']);
    if (!kanji || Number(row['不適切フラグ']) === 1) continue;
    if (reviews[kanji] && !reviews[kanji].reviewBasis) continue;

    const standard = clean(row['標準字体']);
    const standardReview = standard && reviews[standard];
    const text = standardReview
      ? variantText(row, standardReview)
      : `${factSentence(kanji, row['意味'])}${namingSentence(row)}`;

    reviews[kanji] = {
      status: 'reviewed',
      text,
      reviewBasis: standardReview ? 'standard-form-reviewed-text' : 'master-meaning-grounded',
    };
    added += 1;
  }

  reviewFile.entries = reviews;
  fs.writeFileSync(REVIEW_PATH, `${JSON.stringify(reviewFile, null, 2)}\n`, 'utf8');
  console.log(`Added ${added} grounded reviews (${Object.keys(reviews).length} total).`);
}

main();
