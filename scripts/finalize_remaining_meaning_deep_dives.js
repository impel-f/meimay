function clean(value) {
  return String(value || '').replace(/\s+/g, ' ').trim();
}

function meaningParts(value) {
  return clean(value)
    .split('。')
    .map((part) => part.trim())
    .filter(Boolean);
}

function factSentence(kanji, meaning) {
  const parts = meaningParts(meaning);
  if (parts.length === 1) return `「${kanji}」は、「${parts[0]}」を表す字です。`;
  const quoted = parts.map((part) => `「${part}」`).join('、');
  return `「${kanji}」には、${quoted}などの意味があります。`;
}

